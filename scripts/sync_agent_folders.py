#!/usr/bin/env python3
"""Generate the tool-specific folders from the single source of truth.

Source (edit these):            Generated (do not edit):
  skills/<group>/<skill>/        .claude/skills/<skill>/   and  .github/skills/<skill>/
  agents/<name>.md               .claude/agents/<name>.md  and  .github/agents/<name>.agent.md
  prompts/<name>.md              .claude/commands/<name>.md and .github/prompts/<name>.prompt.md

Skills are grouped by tool in `skills/` (core, databricks, github, ...). Agents load them
one level deep, so the group folder is flattened. Skill names must be unique across groups.
Real copies are used instead of symlinks so a clone works on Windows too.

Usage:
  python scripts/sync_agent_folders.py          # regenerate
  python scripts/sync_agent_folders.py --check  # exit 1 if generated folders are stale
"""

import argparse
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BANNER = "<!-- GENERATED by scripts/sync_agent_folders.py. Edit the source file, not this copy. -->\n"


def with_banner(text: str) -> str:
    """Put the banner after the YAML frontmatter so the frontmatter stays first."""
    if text.startswith("---\n"):
        end = text.find("\n---\n", 4)
        if end != -1:
            return text[: end + 5] + BANNER + text[end + 5 :]
    return BANNER + text


def expected() -> dict[Path, bytes]:
    """Map every generated file path to the bytes it must contain."""
    out: dict[Path, bytes] = {}
    names: dict[str, Path] = {}
    for skill_md in sorted((ROOT / "skills").glob("*/*/SKILL.md")):
        skill_dir = skill_md.parent
        if skill_dir.name in names:
            sys.exit(f"Duplicate skill name '{skill_dir.name}': {names[skill_dir.name]} and {skill_dir}")
        names[skill_dir.name] = skill_dir
        for f in sorted(skill_dir.rglob("*")):
            if not f.is_file():
                continue
            rel = f.relative_to(skill_dir)
            data = f.read_bytes()
            if f == skill_md:
                data = with_banner(data.decode("utf-8")).encode("utf-8")
            for base in (".claude/skills", ".github/skills"):
                out[ROOT / base / skill_dir.name / rel] = data
    for f in sorted((ROOT / "agents").glob("*.md")):
        data = with_banner(f.read_text(encoding="utf-8")).encode("utf-8")
        out[ROOT / ".claude/agents" / f.name] = data
        out[ROOT / ".github/agents" / f"{f.stem}.agent.md"] = data
    for f in sorted((ROOT / "prompts").glob("*.md")):
        data = with_banner(f.read_text(encoding="utf-8")).encode("utf-8")
        out[ROOT / ".claude/commands" / f.name] = data
        out[ROOT / ".github/prompts" / f"{f.stem}.prompt.md"] = data
    return out


GENERATED_DIRS = [
    ".claude/skills", ".claude/agents", ".claude/commands",
    ".github/skills", ".github/agents", ".github/prompts",
]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated folders are stale")
    args = parser.parse_args()
    want = expected()
    existing = {p for d in GENERATED_DIRS for p in (ROOT / d).rglob("*") if p.is_file()}
    stale = sorted(p for p in existing if p not in want)
    missing = sorted(p for p, data in want.items() if not p.exists() or p.read_bytes() != data)
    if args.check:
        for p in missing:
            print(f"out of date: {p.relative_to(ROOT)}")
        for p in stale:
            print(f"stale (no source): {p.relative_to(ROOT)}")
        if missing or stale:
            print("Run: python scripts/sync_agent_folders.py")
            return 1
        print("Generated folders are in sync.")
        return 0
    for d in GENERATED_DIRS:
        shutil.rmtree(ROOT / d, ignore_errors=True)
    for path, data in want.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    print(f"Synced {len(want)} files.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
